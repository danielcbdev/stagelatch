/// Writes the user-facing rule reference `docs/rules.md` from the rules the
/// registered checks declare.
///
/// Usage: `dart run tool/generate_rules_doc.dart`, from the repository root.
/// `test/docs/rules_reference_test.dart` fails when the file is stale.
library;

import 'dart:io';

import 'package:stagelatch/src/cli/composition.dart';
import 'package:stagelatch/src/domain/check.dart';

/// Where the reference is written.
const String rulesDocPath = 'docs/rules.md';

/// The command that regenerates the file, written in its first lines.
const String generatorCommand = 'dart run tool/generate_rules_doc.dart';

/// The text of the rule reference for [checks], in their order.
///
/// The output uses LF and ends with one newline.
String renderRulesDoc(List<Check> checks) {
  final out = StringBuffer()
    ..writeln('<!--')
    ..writeln('  Generated by `$generatorCommand`. Do not edit by hand.')
    ..writeln('  It is rebuilt from the rules each check declares, and a test')
    ..writeln('  fails when this file is out of date.')
    ..writeln('-->')
    ..writeln()
    ..writeln('# Rule reference')
    ..writeln()
    ..writeln(
      'Every rule has an ID of the form `<check>/<rule>`. The same ID is '
      'used in the hook lists, in `rules:`, in ignore comments and in the '
      'baseline.',
    )
    ..writeln()
    ..writeln(
      '- **Change a severity** in `stagelatch.yaml`: '
      '`rules: { tests/new-skip: off }` (`error`, `warning` or `off`).',
    )
    ..writeln(
      '- **Suppress one finding** with a comment on its line or the '
      'line before: `// stagelatch:ignore <rule-id>` in Dart, '
      '`# stagelatch:ignore <rule-id>` in YAML.',
    )
    ..writeln(
      '- **Accept the findings a legacy codebase already has** with '
      '`stagelatch baseline create`.',
    )
    ..writeln(
      '- **`stagelatch/invalid-ignore`** (warning) is reported by the tool '
      'itself, not by a check, when an ignore comment names an unknown rule.',
    );
  for (final check in checks) {
    out
      ..writeln()
      ..writeln('## `${check.id}`')
      ..writeln();
    final phase = switch (check.phase) {
      CheckPhase.fix => 'Runs first and may fix files in the index.',
      CheckPhase.verify => 'Reports findings.',
    };
    out.writeln(phase);
    if (check.hasDynamicRules) {
      out
        ..writeln()
        ..writeln(
          "Reports the diagnostics of your SDK's analyzer, one rule per "
          'diagnostic code: `${check.id}/<analyzer code>`. Which ones block '
          'is set by `analyze.fail_on`.',
        );
    }
    if (check.rules.isEmpty) continue;
    out
      ..writeln()
      ..writeln('| Rule | Default | Fix | Reports |')
      ..writeln('|---|---|---|---|');
    for (final rule in check.rules) {
      final fix = rule.fixable ? 'yes' : 'no';
      out.writeln(
        '| `${rule.id}` | ${rule.defaultSeverity.name} | $fix | '
        '${rule.summary} |',
      );
    }
  }
  return out.toString();
}

void main() {
  File(rulesDocPath).writeAsStringSync(renderRulesDoc(productionChecks));
  stdout.writeln('Wrote $rulesDocPath.');
}
