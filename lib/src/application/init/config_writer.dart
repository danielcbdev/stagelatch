/// Renders the `stagelatch.yaml` that `init` writes.
library;

import 'package:stagelatch/src/application/config/check_catalog.dart';
import 'package:stagelatch/src/application/config/default_hooks.dart';
import 'package:stagelatch/src/application/config/hook_selector.dart';
import 'package:stagelatch/src/application/init/project_detector.dart';

/// The configuration for [project], limited to checks [catalog] has and
/// that the detection says are relevant.
///
/// The text uses LF and ends with one newline. Each section has one
/// comment line.
String renderConfig(
  DetectedProject project,
  CheckCatalog catalog, {
  required String toolVersion,
}) {
  final preCommit = _relevant(
    defaultHookSelectors(preCommitHook, catalog),
    project,
  );
  final prePush = _relevant(
    defaultHookSelectors(prePushHook, catalog),
    project,
  );
  return '''
# Generated by `stagelatch init`.
min_version: $toolVersion

# Which checks run on each hook.
hooks:
  pre-commit: [${preCommit.join(', ')}]
  pre-push: [${prePush.join(', ')}]
''';
}

List<HookSelector> _relevant(
  List<HookSelector> selectors,
  DetectedProject project,
) => [
  for (final selector in selectors)
    if (_applies(selector, project)) selector,
];

bool _applies(HookSelector selector, DetectedProject project) =>
    switch (selector.check) {
      'codegen' => project.usesCodegen,
      'l10n' => project.usesL10n,
      'assets' => project.usesAssets,
      _ => true,
    };
